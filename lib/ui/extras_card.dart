/// Trim, subtitles, thumbnail and audio-tag options for the current video.
class ExtrasCard extends StatefulWidget {
  const ExtrasCard({
    super.key,
    required this.extras,
    required this.duration,
    required this.loadTracks,
  });

  final Extras extras;
  final Duration? duration;
  final Future<List<ClosedCaptionTrackInfo>> Function() loadTracks;

  @override
  State<ExtrasCard> createState() => _ExtrasCardState();
}

class _ExtrasCardState extends State<ExtrasCard> {
  bool _open = false;
  List<ClosedCaptionTrackInfo>? _tracks;
  bool _loading = false;

  late final TextEditingController _startCtl =
      TextEditingController(text: fmtDuration(widget.extras.trimStart));
  late final TextEditingController _endCtl =
      TextEditingController(text: fmtDuration(widget.extras.trimEnd));

  @override
  void dispose() {
    _startCtl.dispose();
    _endCtl.dispose();
    super.dispose();
  }

  void _syncFields() {
    final x = widget.extras;
    _startCtl.text = fmtDuration(x.trimStart);
    _endCtl.text = fmtDuration(x.trimEnd);
  }

  Future<void> _find() async {
    setState(() => _loading = true);
    final list = await widget.loadTracks();
    if (!mounted) return;
    setState(() {
      _tracks = list;
      _loading = false;
    });
  }

  String get _summary {
    final x = widget.extras;
    final parts = <String>[];
    final tr = x.trimFor(widget.duration);
    if (tr != null) {
      parts.add('Trim ${fmtDuration(tr.start)}–${fmtDuration(tr.end)}');
    }
    if (x.subtitle != null) parts.add('Subs ${x.subtitle!.language.code}');
    if (x.thumbnail) parts.add('Thumbnail');
    return parts.isEmpty
        ? 'Trim, subtitles, thumbnail, audio tags'
        : parts.join(' · ');
  }

  String _trackName(ClosedCaptionTrackInfo t) {
    final n = t.language.name.isEmpty ? t.language.code : t.language.name;
    return t.isAutoGenerated ? '$n (auto)' : n;
  }

  @override
  Widget build(BuildContext context) {
    final cs = Theme.of(context).colorScheme;
    return SoftCard(
      child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
        InkWell(
          onTap: () => setState(() => _open = !_open),
          child: Row(children: [
            Icon(Icons.auto_fix_high, color: cs.primary),
            const SizedBox(width: 12),
            Expanded(
              child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                Text('Extras',
                    style: Theme.of(context)
                        .textTheme
                        .titleSmall
                        ?.copyWith(fontWeight: FontWeight.w700)),
                Text(_summary,
                    maxLines: 2,
                    overflow: TextOverflow.ellipsis,
                    style: Theme.of(context).textTheme.bodySmall),
              ]),
            ),
            Icon(_open ? Icons.expand_less : Icons.expand_more),
          ]),
        ),
        AnimatedSize(
          duration: const Duration(milliseconds: 220),
          alignment: Alignment.topCenter,
          child: _open
              ? _body(context)
              : const SizedBox(width: double.infinity),
        ),
      ]),
    );
  }

  Widget _body(BuildContext context) {
    final x = widget.extras;
    final cs = Theme.of(context).colorScheme;
    final small = Theme.of(context)
        .textTheme
        .bodySmall
        ?.copyWith(color: cs.onSurfaceVariant);
    return Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
      const SizedBox(height: 8),
      const Divider(height: 1),
      _trimSection(context, small),
      const Divider(height: 1),
      _subsSection(context, small),
      const Divider(height: 1),
      SwitchListTile(
        contentPadding: EdgeInsets.zero,
        title: const Text('Save thumbnail'),
        subtitle: const Text('Saves the cover image next to the file'),
        value: x.thumbnail,
        onChanged: (v) => setState(() => x.thumbnail = v),
      ),
      SwitchListTile(
        contentPadding: EdgeInsets.zero,
        title: const Text('Tag audio files'),
        subtitle: const Text(
            'Adds title, artist and cover art to audio-only downloads'),
        value: x.tags,
        onChanged: (v) => setState(() => x.tags = v),
      ),
    ]);
  }

  Widget _trimSection(BuildContext context, TextStyle? small) {
    final x = widget.extras;
    final total = widget.duration;
    if (total == null || total.inSeconds < 2) {
      return ListTile(
        contentPadding: EdgeInsets.zero,
        leading: const Icon(Icons.content_cut),
        title: const Text('Trim / clip'),
        subtitle: const Text('Not available for live streams'),
        enabled: false,
      );
    }
    final maxS = total.inSeconds.toDouble();
    final bad = x.trimEnd <= x.trimStart;
    return Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
      SwitchListTile(
        contentPadding: EdgeInsets.zero,
        title: const Text('Trim / clip'),
        subtitle: const Text('Keep only a part of the video'),
        value: x.trimOn,
        onChanged: (v) => setState(() {
          x.trimOn = v;
          if (v && x.trimEnd <= x.trimStart) {
            x.trimStart = Duration.zero;
            x.trimEnd = total;
          }
          _syncFields();
        }),
      ),
      if (x.trimOn) ...[
        RangeSlider(
          min: 0,
          max: maxS,
          values: RangeValues(
            x.trimStart.inSeconds.toDouble().clamp(0.0, maxS).toDouble(),
            x.trimEnd.inSeconds.toDouble().clamp(0.0, maxS).toDouble(),
          ),
          onChanged: (r) => setState(() {
            x.trimStart = Duration(seconds: r.start.round());
            x.trimEnd = Duration(seconds: r.end.round());
            _syncFields();
          }),
        ),
        Row(children: [
          Expanded(
            child: TextField(
              controller: _startCtl,
              keyboardType: TextInputType.datetime,
              decoration: const InputDecoration(
                labelText: 'Start',
                helperText: 'm:ss or h:mm:ss',
                border: OutlineInputBorder(),
                isDense: true,
              ),
              onChanged: (v) {
                final d = parseTimeInput(v);
                if (d != null && d <= total) setState(() => x.trimStart = d);
              },
            ),
          ),
          const SizedBox(width: 12),
          Expanded(
            child: TextField(
              controller: _endCtl,
              keyboardType: TextInputType.datetime,
              decoration: const InputDecoration(
                labelText: 'End',
                helperText: 'm:ss or h:mm:ss',
                border: OutlineInputBorder(),
                isDense: true,
              ),
              onChanged: (v) {
                final d = parseTimeInput(v);
                if (d != null && d <= total) setState(() => x.trimEnd = d);
              },
            ),
          ),
        ]),
        const SizedBox(height: 8),
        Text(
          bad
              ? 'The end must be after the start'
              : 'Length: ${fmtDuration(x.trimEnd - x.trimStart)}. The whole '
                  'video is downloaded first, then cut without re-encoding; '
                  'the start snaps to the nearest earlier keyframe.',
          style: bad ? small?.copyWith(color: cs(context).error) : small,
        ),
        const SizedBox(height: 8),
      ],
    ]);
  }

  ColorScheme cs(BuildContext context) => Theme.of(context).colorScheme;

  Widget _subsSection(BuildContext context, TextStyle? small) {
    final x = widget.extras;
    return Padding(
      padding: const EdgeInsets.symmetric(vertical: 12),
      child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
        Row(children: [
          const Icon(Icons.subtitles_outlined),
          const SizedBox(width: 12),
          Expanded(
            child: Text('Subtitles',
                style: Theme.of(context).textTheme.titleSmall),
          ),
          if (_tracks == null)
            TextButton.icon(
              onPressed: _loading ? null : _find,
              icon: _loading
                  ? const SizedBox(
                      width: 14,
                      height: 14,
                      child: CircularProgressIndicator(strokeWidth: 2),
                    )
                  : const Icon(Icons.search, size: 18),
              label: Text(_loading ? 'Looking…' : 'Find'),
            ),
        ]),
        if (_tracks != null && _tracks!.isEmpty)
          Padding(
            padding: const EdgeInsets.only(top: 8),
            child: Text('No subtitles available for this video', style: small),
          ),
        if (_tracks != null && _tracks!.isNotEmpty) ...[
          const SizedBox(height: 8),
          Wrap(spacing: 8, runSpacing: 4, children: [
            ChoiceChip(
              label: const Text('None'),
              selected: x.subtitle == null,
              onSelected: (_) => setState(() => x.subtitle = null),
            ),
            for (final t in _tracks!)
              ChoiceChip(
                label: Text(_trackName(t)),
                selected: x.subtitle == t,
                onSelected: (_) => setState(() => x.subtitle = t),
              ),
          ]),
          const SizedBox(height: 6),
          Text('Saved as an .srt file next to the video', style: small),
        ],
      ]),
    );
  }
}

/// Chapters parsed from the description, each downloadable on its own.
class ChaptersCard extends StatefulWidget {
  const ChaptersCard({
    super.key,
    required this.chapters,
    required this.total,
    required this.onDownload,
  });

  final List<Chapter> chapters;
  final Duration total;
  final void Function(Chapter chapter, Duration end) onDownload;

  @override
  State<ChaptersCard> createState() => _ChaptersCardState();
}

class _ChaptersCardState extends State<ChaptersCard> {
  bool _all = false;

  Duration _end(int i) => i + 1 < widget.chapters.length
      ? widget.chapters[i + 1].start
      : widget.total;

  @override
  Widget build(BuildContext context) {
    final cs = Theme.of(context).colorScheme;
    final list = widget.chapters;
    final count = _all ? list.length : (list.length > 5 ? 5 : list.length);
    return SoftCard(
      child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
        Row(children: [
          Icon(Icons.bookmarks_outlined, color: cs.primary),
          const SizedBox(width: 12),
          Expanded(
            child: Text('Chapters (${list.length})',
                style: Theme.of(context)
                    .textTheme
                    .titleSmall
                    ?.copyWith(fontWeight: FontWeight.w700)),
          ),
        ]),
        const SizedBox(height: 4),
        for (var i = 0; i < count; i++)
          ListTile(
            dense: true,
            contentPadding: EdgeInsets.zero,
            leading: SizedBox(
              width: 54,
              child: Text(fmtDuration(list[i].start),
                  style: const TextStyle(fontWeight: FontWeight.w700)),
            ),
            title: Text(list[i].title,
                maxLines: 2, overflow: TextOverflow.ellipsis),
            subtitle: Text(fmtDuration(_end(i) - list[i].start)),
            trailing: IconButton(
              tooltip: 'Download this chapter',
              icon: const Icon(Icons.download_rounded),
              onPressed: () => widget.onDownload(list[i], _end(i)),
            ),
          ),
        if (list.length > 5)
          Align(
            alignment: Alignment.centerLeft,
            child: TextButton(
              onPressed: () => setState(() => _all = !_all),
              child: Text(_all ? 'Show fewer' : 'Show all ${list.length}'),
            ),
          ),
      ]),
    );
  }
}